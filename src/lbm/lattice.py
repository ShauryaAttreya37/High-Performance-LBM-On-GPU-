"""D2Q9 velocity set: the single source of truth for lattice constants.

Every Python module and every CUDA kernel takes its lattice constants from
here. The CUDA preamble is generated from these values when a kernel is
compiled, so the CPU reference and the GPU kernels can never disagree.

Direction numbering (x to the right, y up)::

    6   2   5
      \\ | /
    3 - 0 - 1
      / | \\
    7   4   8

Weights: w0 = 4/9 (rest), w1..w4 = 1/9 (axis), w5..w8 = 1/36 (diagonal).
Lattice speed of sound: cs^2 = 1/3 in lattice units (dx = dt = 1).

These weights make the discrete velocity moments match those of the
continuous Maxwell-Boltzmann distribution up to fourth order::

    sum_i w_i                     = 1
    sum_i w_i c_ia                = 0
    sum_i w_i c_ia c_ib           = cs^2 delta_ab
    sum_i w_i c_ia c_ib c_ic      = 0
    sum_i w_i c_ia c_ib c_ic c_id = cs^4 (d_ab d_cd + d_ac d_bd + d_ad d_bc)

which is exactly what the Chapman-Enskog expansion needs to recover the
weakly compressible Navier-Stokes equations.
"""

from __future__ import annotations

import numpy as np

Q = 9
"""Number of discrete velocities."""

D = 2
"""Spatial dimensions."""

CS2 = 1.0 / 3.0
"""Squared lattice speed of sound, cs^2 = 1/3."""

CX_TUPLE: tuple[int, ...] = (0, 1, 0, -1, 0, 1, -1, -1, 1)
CY_TUPLE: tuple[int, ...] = (0, 0, 1, 0, -1, 1, 1, -1, -1)
W_TUPLE: tuple[float, ...] = (
    4.0 / 9.0,
    1.0 / 9.0,
    1.0 / 9.0,
    1.0 / 9.0,
    1.0 / 9.0,
    1.0 / 36.0,
    1.0 / 36.0,
    1.0 / 36.0,
    1.0 / 36.0,
)
OPPOSITE_TUPLE: tuple[int, ...] = (0, 3, 4, 1, 2, 7, 8, 5, 6)
"""Index of the velocity pointing the opposite way: c[OPPOSITE[i]] == -c[i]."""


def _read_only(values, dtype) -> np.ndarray:
    array = np.array(values, dtype=dtype)
    array.setflags(write=False)
    return array


# Array views of the same constants, for vectorised NumPy code. Scalar loops use
# the tuples above: Python ints/floats are "weak" scalars under NumPy 2 type
# promotion, so `float32_array * W_TUPLE[i]` stays float32, whereas multiplying
# by a NumPy float64 scalar would silently upcast the whole array.
CX = _read_only(CX_TUPLE, np.int64)
CY = _read_only(CY_TUPLE, np.int64)
W = _read_only(W_TUPLE, np.float64)
OPPOSITE = _read_only(OPPOSITE_TUPLE, np.int64)

_SUPPORTED_REAL_TYPES = ("float", "double")


def _ternary_chain(values) -> str:
    """Render ``i == 0 ? v0 : i == 1 ? v1 : ... : v_last`` for a constexpr accessor."""
    parts = [f"i == {i} ? {v} : " for i, v in enumerate(values[:-1])]
    return "".join(parts) + f"{values[-1]}"


def cuda_preamble(real_type: str) -> str:
    """Return CUDA C++ source declaring ``real_t`` and the D2Q9 constants.

    Constants are emitted as ``constexpr`` accessor functions (``cx(i)``,
    ``cy(i)``, ``opp(i)``, ``weight(i)``) rather than ``__constant__`` arrays.
    Kernels loop over directions with ``#pragma unroll``, which makes ``i`` a
    compile-time constant in every iteration, so the compiler folds each call
    into an immediate value. Per-thread arrays such as ``real_t f[Q]`` are then
    indexed only by constants and can live entirely in registers. Indexing a
    ``__constant__`` array would be a runtime load, and indexing ``f[opp[i]]``
    with a runtime value would push ``f`` out to (slow) local memory.

    Args:
        real_type: ``"float"`` or ``"double"``; becomes ``typedef ... real_t``.

    Returns:
        Source text to prepend to every kernel file.
    """
    if real_type not in _SUPPORTED_REAL_TYPES:
        raise ValueError(f"unsupported real type {real_type!r}; use one of {_SUPPORTED_REAL_TYPES}")
    weights = [f"(real_t){w!r}" for w in W_TUPLE]
    return "\n".join(
        [
            "// ---- Generated by lbm.lattice.cuda_preamble(); do not edit by hand. ----",
            f"typedef {real_type} real_t;",
            f"#define Q {Q}",
            f"__host__ __device__ constexpr int cx(int i) {{ return {_ternary_chain(CX_TUPLE)}; }}",
            f"__host__ __device__ constexpr int cy(int i) {{ return {_ternary_chain(CY_TUPLE)}; }}",
            "__host__ __device__ constexpr int opp(int i) "
            f"{{ return {_ternary_chain(OPPOSITE_TUPLE)}; }}",
            "__host__ __device__ constexpr real_t weight(int i) "
            f"{{ return {_ternary_chain(weights)}; }}",
            "// ---- End of generated preamble. ----",
            "",
        ]
    )
